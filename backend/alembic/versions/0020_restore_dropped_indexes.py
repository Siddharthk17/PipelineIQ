def _is_postgresql() -> bool:
    # op.get_context().dialect works online AND in offline (--sql) mode;
    # op.get_bind() does not (MockConnection has no inspector).
    ctx = op.get_context()
    return bool(ctx.dialect is not None) and ctx.dialect.name == "postgresql"


